package com.combo.feature.builder.draft

/**
 * Пресет раскладки активного фото внутри рамки (кнопки «Fit» и «Fill» тулбара).
 *
 * - [FIT] — фото целиком, с полями; поля заливаются цветом фото;
 * - [FILL] — фото заполняет рамку целиком, лишнее обрезается.
 *
 * Лежит в `draft/`, рядом с [DraftEditor], который его применяет: пакет `draft` не
 * должен зависеть от пакета редактора, иначе пакеты ссылаются друг на друга по кругу
 * (это проверяет `ArchitectureRulesTest`).
 */
enum class FitPreset { FIT, FILL }
