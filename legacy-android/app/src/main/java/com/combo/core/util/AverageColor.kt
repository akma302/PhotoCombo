package com.combo.core.util

import android.graphics.Bitmap

/**
 * Средний цвет изображения. Считается один раз при импорте фото и дальше хранится в
 * `PhotoEntity.avgColor`; при отрисовке не пересчитывается.
 */
object AverageColor {
    /**
     * Сжимает изображение до одного пикселя с билинейной фильтрацией. Это ПРИБЛИЖЕНИЕ к
     * среднему, а не точное среднее по всем пикселям: при таком сильном уменьшении фильтр
     * учитывает лишь часть пикселей, и результат зависит от реализации на устройстве.
     * Цвет используется для фона и заливки полей, поэтому точность не критична.
     */
    fun of(src: Bitmap): Int = Bitmap.createScaledBitmap(src, 1, 1, true).getPixel(0, 0)
}
