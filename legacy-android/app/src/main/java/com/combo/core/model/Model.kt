package com.combo.core.model

/*
 * Общие перечисления предметной области. Пакет ничего не импортирует из `com.combo.*`
 * (это проверяет `ArchitectureRulesTest`), поэтому их можно использовать в любом слое.
 *
 * Имена значений — часть формата хранения: они пишутся в Room строкой через `.name` и
 * читаются через `valueOf`. Переименование значения сломает уже сохранённые комбо.
 */

/** Как меняются фото в рамке: вручную, по таймеру или обоими способами. */
enum class SwitchMode { MANUAL, AUTO, MANUAL_AUTO }

/**
 * Направление смены фото и переходов. `UP`/`DOWN` меняют фото (свайп вверх показывает
 * следующее). `LEFT`/`RIGHT` умеет рисовать отрисовка переходов, но сменой фото они не
 * являются: горизонтальный свайп фото не переключает.
 */
enum class Direction { UP, DOWN, LEFT, RIGHT }

/**
 * Эффект перехода между фото. `durationMs == 0` — перехода нет, фото меняется сразу.
 * Порядок значений — порядок, в котором кнопки тулбара перебирают их по кругу.
 */
enum class TransitionType(val durationMs: Long) {
    NONE(0), FADE(300), SLIDE(300), ZOOM(300), WIPE(300);
}

/**
 * Как фото вписывается в рамку:
 * - `FREE` — масштаб и сдвиг берутся из сохранённых значений;
 * - `FIT` — масштаб и сдвиг вычисляются при каждой отрисовке (фото вписано целиком),
 *   сохранённые значения не показываются. При выходе из `FIT` в них записывается то, что
 *   было на экране, чтобы фото не «прыгало».
 */
enum class FramingMode { FREE, FIT }
